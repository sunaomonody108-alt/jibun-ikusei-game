// ボス5体で1章
export const CHAPTERS = [
  { title: "めざめ", text: "記憶のない分身が 目をさました。まずは 動きだすことから。" },
  { title: "かけらの意味", text: "もどった記憶が 少しずつ つながりはじめた。" },
  { title: "未来の自分", text: "かけらの先に 「なりたい自分」の すがたが 見えてきた。" },
];

export function chapterOf(bossesDefeated) {
  const n = Math.floor(bossesDefeated / BOSSES.length);
  const c = CHAPTERS[Math.min(n, CHAPTERS.length - 1)];
  return { no: n + 1, title: n < CHAPTERS.length ? c.title : "その先へ", text: c.text };
}

